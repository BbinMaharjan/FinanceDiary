export function formatNPR(amount: number, options?: { sign?: '+' | '-' | ''; decimals?: number }): string {
  const sign = options?.sign ?? '';
  const decimals = options?.decimals ?? 0;
  const formatted = amount.toLocaleString('en-IN', { maximumFractionDigits: decimals });
  return `${sign}रू ${formatted}`;
}

export function formatDate(dateStr: string): string {
  const d = new Date(dateStr);
  if (isNaN(d.getTime())) return dateStr;
  return d.toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' });
}

export function toDateInput(dateStr: string): string {
  const d = new Date(dateStr);
  if (isNaN(d.getTime())) return dateStr;
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

